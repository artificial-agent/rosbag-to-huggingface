import os
import ffmpeg
##########################################################################


##########################################################################
prefix = "/Volumes/MY_DATASET/raw-ouputs"
child_dir = "/DATE_TIME/img-rear-center"
output_filename = "MY_VIDEO"
framerate = 30
##########################################################################


##########################################################################
(
    ffmpeg
    .input(f'{prefix}/{child_dir}/*.png', pattern_type='glob', framerate=framerate)
    .output(f'{output_filename}.mp4')
    .run()
)
